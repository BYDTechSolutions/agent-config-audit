/** Every rule, keyed by id. */
export const RULES: ReadonlyMap<string, Rule> = new Map(rules.map((r) => [r.id, r]));

/** Every rule, in report order. */
export const RULE_LIST: readonly Rule[] = rules;

/** Looks up a rule; throws on an unknown id (a bug in a check). */
export function rule(id: string): Rule {
  const r = RULES.get(id);
  if (!r) throw new Error(`Unknown rule id: ${id}`);
  return r;
}

/** The rule's tags, flattened in display order: AST, ASI, LLM, MCP, CWE. */
export function flatTags(r: Rule): string[] {
  const t = r.tags;
  return [
    ...(t.ast ? [t.ast] : []),
    ...(t.asi ?? []),
    ...(t.llm ?? []),
    ...(t.mcp ?? []),
    ...(t.cwe ?? []).map((n) => `CWE-${n}`),
  ];
}
